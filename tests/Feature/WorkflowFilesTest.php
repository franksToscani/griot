<?php

use Symfony\Component\Yaml\Yaml;

/*
 * The GitHub Actions workflows (issue #57, docs/ci.md): the "ci" job of tests.yml that the
 * protection of main requires, and the three jobs of production-checks.yml. They run only on
 * GitHub: this test reads them, so that a change that weakens them shows up here first.
 */

const WF_JOBS = ['ci', 'audit', 'production-build', 'tests-postgres'];

/**
 * A workflow, parsed.
 *
 * @return array<string, mixed>
 */
function wfParse(string $file): array
{
    $workflow = Yaml::parseFile(base_path(".github/workflows/{$file}"));
    expect($workflow)->toBeArray();

    return $workflow;
}

/**
 * A workflow as text.
 */
function wfText(string $file): string
{
    return (string) file_get_contents(base_path(".github/workflows/{$file}"));
}

/**
 * A job of production-checks.yml.
 *
 * @return array<string, mixed>
 */
function wfJob(string $name): array
{
    $job = wfParse('production-checks.yml')['jobs'][$name] ?? null;
    expect($job)->toBeArray("No job {$name} in production-checks.yml");

    return $job;
}

/**
 * The commands of a job, step after step, in one text.
 *
 * @param  array<string, mixed>  $job
 */
function wfRuns(array $job): string
{
    return implode("\n", array_map(fn (array $step) => (string) ($step['run'] ?? ''), $job['steps']));
}

/**
 * The step of a job that uses an action, for example "actions/cache".
 *
 * @param  array<string, mixed>  $job
 * @return array<string, mixed>|null
 */
function wfStepUsing(array $job, string $action): ?array
{
    foreach ($job['steps'] as $step) {
        if (str_starts_with((string) ($step['uses'] ?? ''), $action.'@')) {
            return $step;
        }
    }

    return null;
}

/**
 * Each of the commands appears in the text, in this order.
 *
 * @param  list<string>  $commands
 */
function wfExpectInOrder(string $text, array $commands): void
{
    $position = 0;

    foreach ($commands as $command) {
        $found = strpos($text, $command, $position);
        expect($found)->not->toBeFalse("Missing, or out of order: {$command}");
        $position = (int) $found + strlen($command);
    }
}

test('the ci job of tests.yml keeps its name and runs composer ci:check', function () {
    $workflow = wfParse('tests.yml');
    $ci = $workflow['jobs']['ci'] ?? null;

    // The name of the check is the id of the job when the job has no "name".
    expect($ci)->toBeArray()
        ->and($ci)->not->toHaveKey('name')
        ->and(array_keys($workflow['jobs']))->toBe(['ci'])
        ->and(wfRuns($ci))->toContain('composer ci:check');
});

test('every workflow reads the repository only, never continues on an error and has no secret or contact', function (string $file) {
    $workflow = wfParse($file);
    $text = wfText($file);

    expect($workflow['permissions'])->toBe(['contents' => 'read']);

    foreach ($workflow['jobs'] as $name => $job) {
        expect($job)->not->toHaveKey('permissions', "The job {$name} widens the permissions")
            ->and($job)->not->toHaveKey('continue-on-error');
    }

    expect($text)->not->toContain('continue-on-error')
        ->and($text)->not->toContain('|| true')
        ->and($text)->not->toContain('secrets.')
        // A key written in the file, instead of generated by the job.
        ->and(preg_match('/base64:[A-Za-z0-9+\/]{20,}/', $text))->toBe(0)
        ->and(preg_match('/\+\d{2}[\s\d]{6,}/', $text))->toBe(0);

    preg_match_all('/[\w.+-]+@[\w-]+(?:\.[\w-]+)+/', $text, $addresses);
    foreach ($addresses[0] as $address) {
        // "owner/action@sha" is not an address; every address is on example.test.
        expect(str_ends_with($address, '@example.test') || preg_match('/@[0-9a-f]{40}$/', $address) === 1)->toBeTrue("A real address? {$address}");
    }
})->with(['tests.yml', 'production-checks.yml']);

test('every action is pinned to a commit, the same one in every workflow', function () {
    $commits = [];

    foreach (['tests.yml', 'production-checks.yml'] as $file) {
        foreach (wfParse($file)['jobs'] as $job) {
            foreach ($job['steps'] as $step) {
                if (! isset($step['uses'])) {
                    continue;
                }

                expect(preg_match('/^([\w.-]+\/[\w.-]+)@([0-9a-f]{40})$/', $step['uses'], $match))->toBe(1, "Not pinned to a commit: {$step['uses']}");
                $commits[$match[1]][$match[2]] = true;
            }
        }
    }

    expect(array_keys($commits))->toContain('actions/checkout', 'shivammathur/setup-php', 'actions/setup-node', 'actions/cache');

    foreach ($commits as $action => $shas) {
        expect($shas)->toHaveCount(1, "{$action} has more than one version");
    }
});

test('the audit job fails on the advisories of Composer and npm, with caches, and old runs are cancelled', function () {
    $workflow = wfParse('production-checks.yml');
    $audit = wfJob('audit');
    $runs = wfRuns($audit);

    expect($workflow['concurrency']['group'])->toContain('${{ github.ref }}')
        ->and($workflow['concurrency'])->toHaveKey('cancel-in-progress');

    // Whole commands, one per line: nothing after them that could hide the failure.
    expect(array_map('trim', explode("\n", $runs)))->toContain('composer audit', 'composer audit --no-dev', 'npm audit --omit=dev')
        ->and($runs)->toContain('composer install')
        ->and($runs)->toContain('npm ci')
        ->and(wfStepUsing($audit, 'actions/cache'))->not->toBeNull()
        ->and(wfStepUsing($audit, 'actions/setup-node')['with']['cache'] ?? null)->toBe('npm');
});

test('production-build installs without dev, builds, caches the four, migrates, seeds the categories, refuses the rest and answers', function () {
    $job = wfJob('production-build');
    $env = $job['env'];

    expect($env['APP_ENV'])->toBe('production')
        ->and($env['APP_DEBUG'])->toBe('false')
        ->and($env['SESSION_SECURE_COOKIE'])->toBe('true')
        ->and($env['TRUSTED_PROXIES'])->toBeIn(['', '*'])
        ->and($env['MAIL_MAILER'])->not->toBeIn(['log', 'array'])
        ->and($env['MAIL_HOST'])->toEndWith('.test')
        // Generated by the job, never written in the file.
        ->and($env)->not->toHaveKey('APP_KEY')
        ->and(wfStepUsing($job, 'actions/cache'))->not->toBeNull()
        ->and(wfStepUsing($job, 'actions/setup-node')['with']['cache'] ?? null)->toBe('npm');

    wfExpectInOrder(wfRuns($job), [
        'openssl rand -base64 32',
        'composer install --no-dev --optimize-autoloader',
        'npm ci',
        'npm run build',
        'php artisan config:cache',
        'php artisan route:cache',
        'php artisan view:cache',
        'php artisan event:cache',
        'php artisan about',
        'php artisan migrate --force',
        'php artisan db:seed --class=CategorySeeder --force',
        'if php artisan db:seed --force',
        'exit 1',
        "grep -q 'db:seed --class=CategorySeeder --force'",
        'test "$users" = "0"',
        'php artisan serve',
        'for path in /up /; do',
        'if [ "$code" != "200" ]; then',
    ]);
});

test('tests-postgres runs the whole suite on a PostgreSQL service with a health check and pdo_pgsql', function () {
    $job = wfJob('tests-postgres');
    $postgres = $job['services']['postgres'] ?? [];

    expect($postgres['image'] ?? '')->toMatch('/^postgres:\d+$/')
        ->and($postgres['options'] ?? '')->toContain('--health-cmd')
        ->and($postgres['env'])->not->toHaveKey('POSTGRES_PASSWORD')
        ->and(wfStepUsing($job, 'shivammathur/setup-php')['with']['extensions'] ?? '')->toContain('pdo_pgsql')
        ->and($job['env']['DB_CONNECTION'])->toBe('pgsql')
        // The name the test of the database of the tests expects (TechnicalRetentionTest).
        ->and($job['env']['DB_DATABASE'])->toEndWith('_test')
        ->and($job['env']['DB_DATABASE'])->toBe($postgres['env']['POSTGRES_DB'])
        ->and(wfRuns($job))->toContain('php artisan test')
        ->and(wfRuns($job))->not->toContain('migrate');
});

test('phpunit.xml lets the CI choose the database: DB_CONNECTION and DB_DATABASE without force', function () {
    $xml = simplexml_load_file(base_path('phpunit.xml'));
    expect($xml)->not->toBeFalse();

    $variables = [];
    foreach ($xml->php->env as $env) {
        $variables[(string) $env['name']] = ['value' => (string) $env['value'], 'force' => (string) $env['force']];
    }

    expect($variables['DB_CONNECTION'])->toBe(['value' => 'sqlite', 'force' => ''])
        ->and($variables['DB_DATABASE'])->toBe(['value' => ':memory:', 'force' => '']);
});

test('the jobs are exactly the four of docs/ci.md, the names for the protection of main', function () {
    $jobs = [...array_keys(wfParse('tests.yml')['jobs']), ...array_keys(wfParse('production-checks.yml')['jobs'])];
    $docs = (string) file_get_contents(base_path('docs/ci.md'));

    expect($jobs)->toBe(WF_JOBS);

    foreach (WF_JOBS as $name) {
        expect($docs)->toContain("`{$name}`");
    }
});
